"""Scenario boundaries for the two decoration departments."""

SCENE_CONTEXT = {
    "电销获客": (
        "你所在的是装修公司的电销获客部门。当前是电话初次接触，目标是了解装修需求、"
        "判断意向并争取预约到店或量房。不要把对话设定成已经量房或已有设计方案，"
        "不要代替设计师承诺方案、报价或折扣。"
    ),
    "设计师逼单": (
        "你所在的是装修公司的设计师部门。当前客户已进入到店、量房、设计方案或报价沟通阶段；"
        "围绕户型需求、方案取舍、预算顾虑与签约决策交流。不要把对话设定成陌生电话获客，"
        "不要编造实际方案、报价、优惠或交付承诺。"
    ),
}


def scene_context(scene: str | None) -> str:
    return SCENE_CONTEXT.get(scene, "按行业的一般销售沟通场景进行，不假定具体部门或沟通阶段。")
